import logging
from typing import Optional
from fastapi import APIRouter, Query

from app.services.ai.market_intelligence import get_market_intelligence

logger = logging.getLogger(__name__)
router = APIRouter()


@router.get(
    "/intelligence",
    summary="Get live AI-powered market intelligence, news, and sentiment analysis",
    tags=["Market Intelligence"],
)
async def get_market_intelligence_endpoint(
    symbols: Optional[str] = Query(None, description="Comma-separated tickers to filter by, e.g. RELIANCE.NS,TCS.NS"),
    category: str = Query("general", description="News category: general, forex, crypto, merger"),
    limit: int = Query(15, ge=1, le=50, description="Maximum number of news articles to return"),
):
    """
    Returns live financial news from Finnhub with sentiment analysis and
    risk catalyst commentary generated by Google Gemini AI.
    """
    sym_list = [s.strip().upper() for s in symbols.split(",") if s.strip()] if symbols else None
    return await get_market_intelligence(symbols=sym_list, category=category, limit=limit)


@router.get(
    "/intelligence/sentiment",
    summary="Get aggregated AI market sentiment summary",
    tags=["Market Intelligence"],
)
async def get_market_sentiment_endpoint():
    """
    Returns high-level market sentiment breakdown (Bullish/Bearish/Neutral percentages)
    and an AI-generated briefing of prevailing equity market conditions.
    """
    intel = await get_market_intelligence(limit=20)
    return {
        "status": "success",
        "as_of": intel.get("as_of"),
        "data_source": intel.get("data_source"),
        "summary": intel.get("summary"),
    }
